"""Artifact files on local disk.

Layout: <root>/<analysis id>/<capture id>/{screenshot.png, page.html, visible_text.txt}
Paths are built only from identifiers generated by this application. A capture
is written into <root>/.staging/<capture id> and moved into place when complete.
"""

import os
import shutil
import uuid
from pathlib import Path

SCREENSHOT = "screenshot.png"
HTML = "page.html"
TEXT = "visible_text.txt"
_STAGING = ".staging"


def _identifier(value: str) -> str:
    """Only canonical UUIDs become path segments."""
    if str(uuid.UUID(value)) != value:
        raise ValueError("not a canonical identifier")
    return value


class ArtifactStore:
    def __init__(self, root: Path, max_total_bytes: int) -> None:
        self.root = root.resolve()
        self.max_total_bytes = max_total_bytes

    def total_bytes(self) -> int:
        if not self.root.is_dir():
            return 0
        return sum(path.stat().st_size for path in self.root.rglob("*") if path.is_file())

    def is_full(self) -> bool:
        # Nothing is deleted automatically: old captures belong to the user's records.
        return self.total_bytes() >= self.max_total_bytes

    def staging(self, capture_id: str) -> Path:
        path = self.root / _STAGING / _identifier(capture_id)
        path.mkdir(parents=True, exist_ok=True)
        return path

    def commit(self, analysis_id: str, capture_id: str) -> str:
        """Move the staged files into place. Returns the relative directory (with "/")."""
        relative = f"{_identifier(analysis_id)}/{_identifier(capture_id)}"
        target = self.root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        os.replace(self.root / _STAGING / capture_id, target)
        return relative

    def discard(self, capture_id: str) -> None:
        shutil.rmtree(self.root / _STAGING / _identifier(capture_id), ignore_errors=True)

    def discard_all_staging(self) -> None:
        """Left-overs of captures interrupted by a crash or restart."""
        shutil.rmtree(self.root / _STAGING, ignore_errors=True)

    def delete_analysis(self, analysis_id: str) -> None:
        try:
            shutil.rmtree(self.root / _identifier(analysis_id), ignore_errors=True)
        except ValueError:
            return

    def resolve(self, relative: str | None) -> Path | None:
        """A stored relative path -> existing file inside the root, else None."""
        if not relative:
            return None
        path = (self.root / relative).resolve()
        if not path.is_relative_to(self.root) or not path.is_file():
            return None
        return path


def write_file(directory: Path, name: str, data: bytes) -> None:
    """All or nothing: a file either appears complete under its name or not at all."""
    partial = directory / f"{name}.part"
    try:
        partial.write_bytes(data)
        os.replace(partial, directory / name)
    except BaseException:
        partial.unlink(missing_ok=True)
        raise
